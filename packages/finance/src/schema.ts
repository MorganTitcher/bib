export const METRICS = [
  "netRevenue",
  "mrr",
  "newCustomers",
  "activeCustomers",
  "grossProfit",
  "opex",
  "ebitda",
  "netIncome",
  "cash",
  "burn",
] as const
export type Metric = (typeof METRICS)[number]

const twelve = z.array(z.number().positive()).length(12)

export const FinanceModelSchema = z
  .object({
    meta: z.object({
      name: z.string().min(1),
      currency: z
        .string()
        .regex(/^[A-Z]{3}$/, "currency is an ISO 4217 code like USD")
        .default("USD"),
      /** First projected month. Enables `"YYYY-MM"` month references and calendar labels. */
      startMonth: monthKeySchema.optional(),
      horizonMonths: z.number().int().min(1).max(240).default(36),
      /** LTV sums at most this many months of a cohort's life. */
      lifetimeCapMonths: z.number().int().min(1).max(600).default(60),
      /** Annual rate used to discount LTV. */
      discountRateAnnual: zeroRate(),
      /** Provenance assumed for bands that carry none. */
      defaultProvenance: ProvenanceSchema.optional(),
    }),
    opening: z
      .object({
        cash: z.number().finite().default(0),
        receivables: z.number().min(0).default(0),
        payables: z.number().min(0).default(0),
        /** Prepaid revenue already collected from opening customers. Released over 12 months. */
        deferredRevenue: z.number().min(0).default(0),
        taxLossCarryforward: z.number().min(0).default(0),
      })
      .prefault({}),
    streams: z.array(StreamSchema).min(1),
    revenueDeductions: DeductionsSchema.prefault({}),
    channels: z.array(ChannelSchema).default([]),
    costs: CostsSchema.prefault({}),
    workingCapital: z
      .object({
        /** Days sales outstanding: how long customers take to pay. */
        dsoDays: zeroCount(),
        /** Days payables outstanding: how long you take to pay suppliers (not payroll). */
        dpoDays: zeroCount(),
        /** Share of billings never collected, in basis points. */
        badDebtBps: zeroBps(),
      })
      .prefault({}),
    taxes: z.object({ rate: zeroRate() }).prefault({}),
    funding: z.array(FundingEvent).default([]),
    seasonality: z
      .object({
        /** Multipliers on acquired customers, January first. */
        acquisition: twelve.optional(),
        /** Multipliers on usage, services hours and GMV, January first. */
        volume: twelve.optional(),
      })
      .prefault({}),
    events: z.array(OneOffEvent).default([]),
    actuals: z
      .array(z.object({ month: monthRefSchema, metric: z.enum(METRICS), value: z.number() }))
      .default([]),
    scenarios: z
      .array(
        z.object({
          id: idSchema,
          name: z.string().optional(),
          /** Band path → new point, or `"low"`/`"high"` to use the band's own bound. */
          overrides: z.record(z.string(), z.union([z.number(), z.enum(["low", "high"])])),
        }),
      )
      .default([]),
  })
  .superRefine((model, ctx) => {
    const issue = (path: (string | number)[], message: string) =>
      ctx.addIssue({ code: "custom", path, message })

    const unique = (items: readonly { id: string }[], path: string) => {
      const seen = new Set<string>()
      items.forEach((item, i) => {
        if (seen.has(item.id)) issue([path, i, "id"], `duplicate id "${item.id}" in ${path}`)
        seen.add(item.id)
      })
    }
    unique(model.streams, "streams")
    unique(model.channels, "channels")
    unique(model.funding, "funding")
    unique(model.events, "events")
    unique(model.scenarios, "scenarios")
    const costPaths = ["headcount", "opex", "capex"] as const
    for (const key of costPaths) {
      const seen = new Set<string>()
      model.costs[key].forEach((item, i) => {
        if (seen.has(item.id))
          issue(["costs", key, i, "id"], `duplicate id "${item.id}" in costs.${key}`)
        seen.add(item.id)
      })
    }

    const subscriptions = model.streams.filter((s) => s.type === "subscription")
    const subscriptionIds = new Set(subscriptions.map((s) => s.id))
    const checkSub = (ref: string | undefined, path: (string | number)[]) => {
      if (ref !== undefined && !subscriptionIds.has(ref)) {
        issue(path, `"${ref}" is not the id of a subscription stream`)
      }
    }

    model.streams.forEach((stream, i) => {
      switch (stream.type) {
        case "subscription": {
          const mix = stream.tiers.reduce((total, tier) => total + tier.mix.point, 0)
          if (Math.abs(mix - 1) > 1e-6) {
            issue(["streams", i, "tiers"], `tier mix must sum to 1 (got ${mix})`)
          }
          unique(stream.tiers, `streams.${stream.id}.tiers`)
          break
        }
        case "usage":
        case "marketplace":
          checkSub(stream.customersOf, ["streams", i, "customersOf"])
          break
        case "oneTime":
          checkSub(stream.perNewCustomerOf, ["streams", i, "perNewCustomerOf"])
          break
        case "services":
          checkSub(stream.newCustomersOf, ["streams", i, "newCustomersOf"])
          break
      }
    })

    const roles = new Set(model.costs.headcount.map((r) => r.id))
    model.channels.forEach((channel, i) => {
      if (subscriptions.length === 0) {
        issue(
          ["channels", i],
          "channels acquire customers into a subscription stream; add one (a zero-price tier models free accounts)",
        )
      }
      checkSub(channel.stream, ["channels", i, "stream"])
      if (channel.type === "sales" && !roles.has(channel.role)) {
        issue(["channels", i, "role"], `"${channel.role}" is not a headcount role id`)
      }
    })

    if (model.meta.startMonth === undefined) {
      const visit = (value: unknown, path: (string | number)[]) => {
        const key = path.at(-1)
        const isMonthField = key === "month" || key === "start" || key === "end"
        if (typeof value === "string" && isMonthField && isMonthKey(value)) {
          issue(path, `calendar month "${value}" needs meta.startMonth`)
        } else if (Array.isArray(value)) {
          for (const [i, item] of value.entries()) visit(item, [...path, i])
        } else if (value !== null && typeof value === "object") {
          for (const [key, item] of Object.entries(value)) visit(item, [...path, key])
        }
      }
      visit(model, [])
    }
  })

/** A validated model. Every band is resolved to `{ low, point, high }`. */
export type FinanceModel = z.output<typeof FinanceModelSchema>
/** What you write in JSON before validation and defaults. */
export type FinanceModelInput = z.input<typeof FinanceModelSchema>
export type Stream = FinanceModel["streams"][number]
export type SubscriptionStreamModel = Extract<Stream, { type: "subscription" }>
export type Channel = FinanceModel["channels"][number]
export type HeadcountRoleModel = FinanceModel["costs"]["headcount"][number]
export type FundingEventModel = FinanceModel["funding"][number]

/** One validation problem, with a dotted path into the input. */
export interface ModelIssue {
  path: string
  message: string
}

/**
 * Validate and normalize a model. Bare numbers become zero-width bands, defaults
 * are filled in, references are checked, and scenario override paths must name
 * real bands.
 */
export function parseModel(input: unknown): Result<FinanceModel, ModelIssue[]> {
  const parsed = FinanceModelSchema.safeParse(input)
  if (!parsed.success) {
    return err(
      parsed.error.issues.map((issue) => ({
        path: issue.path.map(String).join("."),
        message: issue.message,
      })),
    )
  }
  const model = parsed.data
  const issues: ModelIssue[] = []
  model.scenarios.forEach((scenario, i) => {
    for (const path of Object.keys(scenario.overrides)) {
      if (getBand(model, path) === undefined) {
        issues.push({ path: `scenarios.${i}.overrides`, message: `"${path}" is not a band path` })
      }
    }
  })
  return issues.length > 0 ? err(issues) : ok(model)
}

/** Like {@link parseModel} but throws a `TypeError` listing every issue. */
export function assertModel(input: unknown): FinanceModel {
  const result = parseModel(input)
  if (result.ok) return result.value
  const lines = result.error.map((issue) => `${issue.path || "(root)"}: ${issue.message}`)
  throw new TypeError(`invalid finance model:\n${lines.join("\n")}`)
}
