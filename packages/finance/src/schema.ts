import { err, ok, type Result } from "@bib/shared/result"
import { z } from "zod"
import {
  bandSchema,
  bpsBand,
  countBand,
  growthBand,
  moneyBand,
  ProvenanceSchema,
  rateBand,
} from "./band.ts"
